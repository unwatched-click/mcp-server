/**
 * Wire types of the Unwatched public REST API (`/api/v1`), as JSON arrives over HTTP:
 * dates are ISO strings. Mirrors the backend's `public-api.service.ts`.
 */

export interface UsageInfo {
	creditsCharged: number;
	/** null for callers exempt from billing. */
	creditsRemaining: number | null;
}

export interface VideoInfo {
	videoId: string;
	title: string;
	durationSeconds: number | null;
	thumbnailUrl: string;
	publishedAt: string | null;
}

export interface Segment {
	start: number;
	end: number;
	text: string;
}

export interface SubtitleTrack {
	lang: string;
	langName: string;
	isAutoGenerated: boolean;
	isTranslated: boolean;
	quality: 'high' | 'medium-high' | 'medium' | 'unsupported';
}

/** Either a full YouTube URL or an 11-character video id must be set. */
export interface VideoRef {
	url?: string;
	videoId?: string;
}

export interface SubtitlesResult {
	videoId: string;
	lang: string;
	detectedLang?: string;
	video: VideoInfo;
	segments: Segment[];
	tracks: SubtitleTrack[];
	cached: boolean;
	usage: UsageInfo;
}

export interface TracksResult {
	videoId: string;
	tracks: SubtitleTrack[];
}

export interface Frame {
	seconds: number;
	width: number;
	imageUrl: string;
	mimeType: 'image/webp';
	/** Present only when the caller asked for inline bytes. */
	base64?: string;
	cached: boolean;
}

export interface FramesResult {
	videoId: string;
	video: VideoInfo;
	frames: Frame[];
	usage: UsageInfo;
}

export interface TranslateResult {
	videoId: string;
	sourceLang: string;
	targetLang: string;
	segments: Segment[];
	cached: boolean;
	usage: UsageInfo;
}

export type SummaryLength = 'brief' | 'medium' | 'full';

/** Article body as produced by the backend; the shape is passed through to the agent as-is. */
export type SummaryArticle = Record<string, unknown>;

export interface SummaryResult {
	article: SummaryArticle;
	video: VideoInfo;
	cached: boolean;
	usage: UsageInfo;
}

export interface ArticleSearchItem {
	id: number;
	videoId: string;
	videoUrl: string;
	videoTitle: string;
	articleLang: string;
	title: string | null;
	intro: string | null;
	categories: Array<{ slug: string; label: string }>;
	videoDuration: number | null;
	videoPublishedAt: string | null;
	createdAt: string;
}

export interface ArticleSearchResult {
	articles: ArticleSearchItem[];
	total: number;
	page: number;
	limit: number;
}

/** `GET /api/v1/credits` — balance snapshot; passed through to the agent as-is. */
export type CreditSnapshot = Record<string, unknown>;

/** Error envelope every `/api/v1` failure uses. */
export interface ApiErrorBody {
	error: {
		code: string;
		message: string;
		retryAfterSeconds?: number;
	};
}

export type ApiJobKind = 'summary' | 'translation';

export type ApiJobStatus = 'queued' | 'running' | 'succeeded' | 'failed';

export type ApiJobStage = 'queued' | 'fetching_transcript' | 'generating' | 'saving';

export interface ApiJobProgress {
	stage: ApiJobStage;
	percent: number;
}

export interface ApiJob {
	id: string;
	kind: ApiJobKind;
	status: ApiJobStatus;
	progress: ApiJobProgress | null;
	result?: SummaryResult | TranslateResult;
	error?: {
		code: string;
		message: string;
	};
	creditsCharged: number;
	createdAt: string;
	startedAt: string | null;
	completedAt: string | null;
}
