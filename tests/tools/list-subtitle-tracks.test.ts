import { describe, expect, it } from 'vitest';
import { ApiError } from '../../src/api/errors.js';
import type { TracksResult } from '../../src/api/types.js';
import { listSubtitleTracksHandler } from '../../src/tools/list-subtitle-tracks/handler.js';
import { createFakeApi } from './fake-api.js';

const VIDEO_ID = 'dQw4w9WgXcQ';
const UNAUTHORIZED_TEXT = 'The Unwatched API key is missing or invalid. Set the UNWATCHED_API_KEY environment variable to a valid key (or reconnect the hosted server with a valid key). Get a key at https://unwatched.click/en/developer/keys';

const tracksResult: TracksResult = {
	videoId: VIDEO_ID,
	tracks: [
		{ lang: 'en', langName: 'English', isAutoGenerated: false, isTranslated: false, quality: 'high' },
		{ lang: 'uk', langName: 'Ukrainian', isAutoGenerated: true, isTranslated: false, quality: 'medium' },
	],
};

const TRACKS_JSON = `{
  "videoId": "dQw4w9WgXcQ",
  "tracks": [
    {
      "lang": "en",
      "langName": "English",
      "isAutoGenerated": false,
      "isTranslated": false,
      "quality": "high"
    },
    {
      "lang": "uk",
      "langName": "Ukrainian",
      "isAutoGenerated": true,
      "isTranslated": false,
      "quality": "medium"
    }
  ]
}`;

describe('list_subtitle_tracks handler', () => {
	it('resolves the video id from a URL and returns the tracks as JSON', async () => {
		const api = createFakeApi();
		api.listSubtitleTracks.mockResolvedValue(tracksResult);

		const result = await listSubtitleTracksHandler({ url: 'https://youtu.be/dQw4w9WgXcQ?t=30' }, api);

		expect(api.listSubtitleTracks).toHaveBeenCalledTimes(1);
		expect(api.listSubtitleTracks).toHaveBeenCalledWith('dQw4w9WgXcQ');
		expect(result.isError).toBeUndefined();
		expect(result.content).toEqual([{ type: 'text', text: TRACKS_JSON }]);
	});

	it('accepts a bare videoId and known URL shapes', async () => {
		const api = createFakeApi();
		api.listSubtitleTracks.mockResolvedValue(tracksResult);

		await listSubtitleTracksHandler({ videoId: VIDEO_ID }, api);
		await listSubtitleTracksHandler({ url: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ&list=PL123' }, api);
		await listSubtitleTracksHandler({ url: 'https://www.youtube.com/shorts/dQw4w9WgXcQ' }, api);
		await listSubtitleTracksHandler({ url: 'https://www.youtube.com/embed/dQw4w9WgXcQ' }, api);
		await listSubtitleTracksHandler({ url: VIDEO_ID }, api);

		expect(api.listSubtitleTracks).toHaveBeenNthCalledWith(1, VIDEO_ID);
		expect(api.listSubtitleTracks).toHaveBeenNthCalledWith(2, VIDEO_ID);
		expect(api.listSubtitleTracks).toHaveBeenNthCalledWith(3, VIDEO_ID);
		expect(api.listSubtitleTracks).toHaveBeenNthCalledWith(4, VIDEO_ID);
		expect(api.listSubtitleTracks).toHaveBeenNthCalledWith(5, VIDEO_ID);
	});

	it('returns a tool error without calling the API when both url and videoId are missing', async () => {
		const api = createFakeApi();

		const result = await listSubtitleTracksHandler({}, api);

		expect(result).toEqual({
			content: [{ type: 'text', text: 'url or videoId is required' }],
			isError: true,
		});
		expect(api.listSubtitleTracks).not.toHaveBeenCalled();
	});

	it('rejects a malformed videoId before calling the API', async () => {
		const api = createFakeApi();

		const result = await listSubtitleTracksHandler({ videoId: 'short' }, api);

		expect(result).toEqual({
			content: [{ type: 'text', text: 'videoId must be an 11-character YouTube id' }],
			isError: true,
		});
		expect(api.listSubtitleTracks).not.toHaveBeenCalled();
	});

	it('rejects a URL without an id before calling the API', async () => {
		const api = createFakeApi();

		const result = await listSubtitleTracksHandler({ url: 'https://example.com/no-id' }, api);

		expect(result).toEqual({
			content: [{ type: 'text', text: 'Invalid YouTube URL' }],
			isError: true,
		});
		expect(api.listSubtitleTracks).not.toHaveBeenCalled();
	});

	it('maps UNAUTHORIZED to API-key guidance', async () => {
		const api = createFakeApi();
		api.listSubtitleTracks.mockRejectedValue(new ApiError('UNAUTHORIZED', 'Invalid API key', 401));

		const result = await listSubtitleTracksHandler({ videoId: VIDEO_ID }, api);

		expect(result).toEqual({
			content: [{ type: 'text', text: UNAUTHORIZED_TEXT }],
			isError: true,
		});
	});
});
